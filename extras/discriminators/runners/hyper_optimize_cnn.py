# with all other trials, so memory cost scales only with the number of CNN
# instances (negligible). The practical cap is GIL contention on the Python
# bookkeeping inside the train loop -- past ~16-32 threads, more parallelism
# hurts wall-clock. 50 is too many on a single A40 even with the on-GPU
# refactor; 8-16 is the sweet spot.
