def _train_one_trial(
    trial: optuna.Trial,
    data: dict,
    trace_length: int,
) -> float:
    """Train a single CNN configuration. Returns final validation loss.

    Uses on-GPU indexed sampling (no DataLoader) so the inner loop is just
    `randperm` + tensor indexing + forward/backward/step. Train/val tensors
    are already resident on the GPU; multiple parallel trials share them.
    """
    lr = trial.suggest_float("lr", 1e-5, 5e-3, log=True)
    # Bias toward larger batches: the model is tiny so big batches are
    # essentially free on the A40 and cut per-epoch iteration count
    # proportionally.
    batch_size = trial.suggest_categorical("batch_size", [128, 256, 512, 1024])

    logger.info(
        f"[L={trace_length}] Trial #{trial.number} START  "
        f"lr={lr:.2e}  batch_size={batch_size}"
    )
    trial_t0 = time.perf_counter()

    X_train: torch.Tensor = data["X_train"]   # on DEVICE
    y_train: torch.Tensor = data["y_train"]
    X_val: torch.Tensor = data["X_val"]
    y_val: torch.Tensor = data["y_val"]
    n_train = X_train.shape[0]
    n_val = X_val.shape[0]

    model = CNN(
        in_channels=NUM_QUBITS * 2,
        m_param=M_PARAM,
        num_qubits=NUM_QUBITS,
    ).to(DEVICE)
    criterion = nn.BCEWithLogitsLoss()
    optimizer = optim.Adam(model.parameters(), lr=lr)
    scheduler = optim.lr_scheduler.StepLR(
        optimizer, step_size=DECAY_STEP, gamma=DECAY_RATE
    )

    # Log a couple of epoch milestones so a stuck trial is obvious. With
    # parallel trials these messages interleave; the trial# prefix keeps them
    # readable.
    log_every = max(1, EPOCHS_PER_TRIAL // 3)

    val_loss = float("inf")
    train_loss = float("inf")
    for epoch in range(EPOCHS_PER_TRIAL):
        # ---- train ----
        model.train()
        perm = torch.randperm(n_train, device=DEVICE)
        # Accumulate loss on the GPU; sync once per epoch instead of per batch.
        train_loss_t = torch.zeros((), device=DEVICE)
        for start in range(0, n_train, batch_size):
            idx = perm[start:start + batch_size]
            X_b = X_train[idx]
            y_b = y_train[idx]
            optimizer.zero_grad(set_to_none=True)
            loss = criterion(model(X_b), y_b)
            loss.backward()
            optimizer.step()
            train_loss_t = train_loss_t + loss.detach() * X_b.size(0)
        scheduler.step()
        train_loss = (train_loss_t / n_train).item()

        # ---- val ----
        model.eval()
        val_loss_t = torch.zeros((), device=DEVICE)
        with torch.no_grad():
            for start in range(0, n_val, batch_size):
                X_b = X_val[start:start + batch_size]
                y_b = y_val[start:start + batch_size]
                val_loss_t = val_loss_t + (
                    criterion(model(X_b), y_b) * X_b.size(0)
                )
        val_loss = (val_loss_t / n_val).item()

        if (epoch + 1) % log_every == 0 or epoch == EPOCHS_PER_TRIAL - 1:
            logger.info(
                f"[L={trace_length}] Trial #{trial.number} "
                f"epoch {epoch + 1:>3d}/{EPOCHS_PER_TRIAL}  "
                f"train={train_loss:.4f}  val={val_loss:.4f}  "
                f"lr={scheduler.get_last_lr()[0]:.2e}"
            )

        trial.report(val_loss, epoch)
        if trial.should_prune():
            logger.info(
                f"[L={trace_length}] Trial #{trial.number} PRUNED at epoch "
                f"{epoch + 1}  val={val_loss:.4f}"
            )
            raise optuna.exceptions.TrialPruned()

    # Save weights for the best-trial pickup below. Trial numbers are unique
    # so parallel trials don't collide on the path.
    model_path = os.path.join(
        SAVE_DIR, f"CNN_m{M_PARAM}_len{trace_length}_trial{trial.number}.pth"
    )
    with _FILE_LOCK:
        torch.save(model.state_dict(), model_path)
    trial.set_user_attr("model_path", model_path)
    trial.set_user_attr("ds_factor", data["ds_factor"])
    trial.set_user_attr("wall_time_s", time.perf_counter() - trial_t0)
    return val_loss


def _evaluate_test(
    model: nn.Module,
    X_test: torch.Tensor,
    y_test: torch.Tensor,
    batch_size: int,
):
    """Per-qubit + global accuracy on the test set.

    X_test, y_test are already on the GPU; iterate in contiguous slices.
    """
    model.eval()
    n = X_test.shape[0]
    pred_chunks = []
    with torch.no_grad():
        for start in range(0, n, batch_size):
            X_b = X_test[start:start + batch_size]
            pred_chunks.append(torch.sigmoid(model(X_b)))
    preds = torch.cat(pred_chunks, dim=0).cpu().numpy()
    binary = (preds >= 0.5).astype(int)
    y_int = y_test.cpu().numpy().astype(int)

    per_q = [100.0 * np.mean(binary[:, q] == y_int[:, q]) for q in range(NUM_QUBITS)]
    overall = 100.0 * np.mean(np.all(binary == y_int, axis=1))
    return overall, per_q


