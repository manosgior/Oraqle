def _make_trial_callback(trace_length: int):
    """Return an Optuna callback that logs each completed/pruned/failed trial."""
    def _cb(study: optuna.Study, trial: optuna.trial.FrozenTrial):
        elapsed = trial.user_attrs.get("wall_time_s", None)
        elapsed_s = f"  ({_fmt_dur(elapsed)})" if elapsed is not None else ""

        completed = sum(
            1 for t in study.trials
            if t.state in (
                optuna.trial.TrialState.COMPLETE,
                optuna.trial.TrialState.PRUNED,
                optuna.trial.TrialState.FAIL,
            )
        )

        if trial.state == optuna.trial.TrialState.COMPLETE:
            best_so_far = min(
                (t.value for t in study.trials
                 if t.state == optuna.trial.TrialState.COMPLETE and t.value is not None),
                default=float("inf"),
            )
            logger.success(
                f"[L={trace_length}] Trial #{trial.number} DONE "
                f"({completed}/{N_OPTUNA_TRIALS})  val={trial.value:.6f}  "
                f"best_so_far={best_so_far:.6f}{elapsed_s}"
            )
        elif trial.state == optuna.trial.TrialState.PRUNED:
            logger.info(
                f"[L={trace_length}] Trial #{trial.number} pruned "
                f"({completed}/{N_OPTUNA_TRIALS}){elapsed_s}"
            )
        else:
            logger.error(
                f"[L={trace_length}] Trial #{trial.number} FAILED "
                f"({completed}/{N_OPTUNA_TRIALS}){elapsed_s}"
            )
    return _cb


def optimize_cnn():
    overall_t0 = time.perf_counter()
    summary: list[dict] = []

    logger.info("=" * 78)
    logger.info("CNN Hyper-Optimization")
    logger.info("=" * 78)
    logger.info(f"  device              : {DEVICE}")
    if DEVICE.type == "cuda":
        logger.info(f"  gpu                 : {torch.cuda.get_device_name(0)}")
    logger.info(f"  trace lengths       : {TRACE_LENGTHS}")
    logger.info(f"  target ds-steps     : {TARGET_STEPS}")
    logger.info(f"  trials per length   : {N_OPTUNA_TRIALS}")
    logger.info(f"  parallel trials     : {N_PARALLEL_TRIALS}")
    logger.info(f"  epochs per trial    : {EPOCHS_PER_TRIAL}")
    logger.info(f"  m_param (fixed)     : {M_PARAM}")
    logger.info(f"  search space        : lr ∈ [1e-5, 5e-3], batch_size ∈ "
                f"{{32, 64, 128, 256}}")
    logger.info(f"  save dir            : {SAVE_DIR}")
    logger.info(f"  csv dir             : {CSV_DIR}")
    logger.info(f"  run tag             : {_RUN_TAG}")
    logger.info("=" * 78)

    for li, length in enumerate(TRACE_LENGTHS, start=1):
        if length % TARGET_STEPS != 0:
            logger.warning(
                f"Skipping length={length}: not divisible by TARGET_STEPS={TARGET_STEPS}"
            )
            continue
        ds_factor = length // TARGET_STEPS
        physical_ns = length * 2  # 2 ns / raw sample at 500 MHz
        length_t0 = time.perf_counter()

        logger.info("")
        logger.info("-" * 78)
        logger.info(
            f"[{li}/{len(TRACE_LENGTHS)}] Trace length {length} "
            f"({physical_ns} ns)  |  ds_factor={ds_factor}  ->  "
            f"{TARGET_STEPS} steps"
        )
        logger.info("-" * 78)

        try:
            data = prepare_split_for_length(length)
        except FileNotFoundError as e:
            logger.error(
                f"Missing preprocessed file for length={length}: {e}. "
                "Run `python -m helpers.extract_data_per_length` first."
            )
            return
        logger.info(
            f"Train/val shapes: X_train={tuple(data['X_train'].shape)}  "
            f"X_val={tuple(data['X_val'].shape)}  "
            f"y_train={tuple(data['y_train'].shape)}"
        )
        # Per-channel stats give a quick sanity check that normalization is sane.
        mean_summary = data["mean"].reshape(-1)
        std_summary = data["std"].reshape(-1)
        logger.info(
            f"  per-channel mean range: [{mean_summary.min():.3e}, "
            f"{mean_summary.max():.3e}]  std range: [{std_summary.min():.3e}, "
            f"{std_summary.max():.3e}]"
        )

        sampler = optuna.samplers.TPESampler(seed=SAMPLE_SEED)
        pruner = optuna.pruners.MedianPruner(n_warmup_steps=5)
        study = optuna.create_study(
            direction="minimize", sampler=sampler, pruner=pruner
        )

        logger.info(
            f"Starting Optuna study: {N_OPTUNA_TRIALS} trials, "
            f"{N_PARALLEL_TRIALS} in parallel"
        )
        study_t0 = time.perf_counter()
        study.optimize(
            lambda trial: _train_one_trial(trial, data, length),
            n_trials=N_OPTUNA_TRIALS,
            n_jobs=N_PARALLEL_TRIALS,
            gc_after_trial=True,
            callbacks=[_make_trial_callback(length)],
        )
        study_dur = time.perf_counter() - study_t0

        n_complete = sum(
            1 for t in study.trials
            if t.state == optuna.trial.TrialState.COMPLETE
        )
        n_pruned = sum(
            1 for t in study.trials
            if t.state == optuna.trial.TrialState.PRUNED
        )
        n_failed = sum(
            1 for t in study.trials
            if t.state == optuna.trial.TrialState.FAIL
        )
        logger.info(
            f"Study finished in {_fmt_dur(study_dur)}  |  "
            f"complete={n_complete}  pruned={n_pruned}  failed={n_failed}"
        )

        best = study.best_trial
        logger.success(
            f"BEST trial #{best.number}  val_loss={best.value:.6f}  "
            f"lr={best.params['lr']:.2e}  batch_size={best.params['batch_size']}"
        )

        # Reload best weights and evaluate on the test set.
        logger.info("Reloading best weights and evaluating on test set...")
        best_model = CNN(
            in_channels=NUM_QUBITS * 2,
            m_param=M_PARAM,
            num_qubits=NUM_QUBITS,
        ).to(DEVICE)
        best_model.load_state_dict(
            torch.load(best.user_attrs["model_path"], map_location=DEVICE)
        )
        best_model.eval()

        try:
            X_test, y_test = prepare_test_for_length(
                length, data["mean"], data["std"]
            )
        except FileNotFoundError as e:
            logger.warning(
                f"Test set not available for length={length}: {e}. "
                "Skipping test-set evaluation."
            )
            summary.append({
                "length": length,
                "overall": None,
                "per_q": None,
                "elapsed": time.perf_counter() - length_t0,
            })
            del data, best_model
            if DEVICE.type == "cuda":
                torch.cuda.empty_cache()
            continue

        eval_t0 = time.perf_counter()
        overall_acc, per_q = _evaluate_test(
            best_model, X_test, y_test, batch_size=best.params["batch_size"]
        )
        logger.info(f"Test eval done in {_fmt_dur(time.perf_counter() - eval_t0)}")
        logger.success(
            f"TEST  (len {length}, {physical_ns} ns)  overall={overall_acc:.2f}%  "
            + "  ".join(f"q{i}={per_q[i]:.2f}%" for i in range(NUM_QUBITS))
        )
        _save_csv_report(study, best_model, length, overall_acc, per_q)
        summary.append({
            "length": length,
            "overall": overall_acc,
            "per_q": per_q,
            "elapsed": time.perf_counter() - length_t0,
        })

        # Free GPU memory before moving to the next trace length.
        del data, best_model
        if DEVICE.type == "cuda":
            torch.cuda.empty_cache()
            logger.info(
                f"GPU mem after cleanup: "
                f"allocated={torch.cuda.memory_allocated()/1e9:.2f} GB  "
                f"reserved={torch.cuda.memory_reserved()/1e9:.2f} GB"
            )

        logger.info(
            f"[{li}/{len(TRACE_LENGTHS)}] length={length} finished in "
            f"{_fmt_dur(time.perf_counter() - length_t0)}"
        )

    # -------------- Final summary --------------
    total_elapsed = time.perf_counter() - overall_t0
    logger.info("")
    logger.info("=" * 78)
    logger.info(f"All lengths done in {_fmt_dur(total_elapsed)}")
    logger.info("=" * 78)
    header = (
        f"{'length':>8} {'ns':>6} {'overall':>9} "
        + " ".join(f"q{i:>1}".rjust(7) for i in range(NUM_QUBITS))
        + f"  {'elapsed':>8}"
    )
    logger.info(header)
    logger.info("-" * len(header))
    for row in summary:
        if row["overall"] is None:
            line = (
                f"{row['length']:>8} {row['length']*2:>6} "
                f"{'n/a':>9} "
                + " ".join(f"{'n/a':>7}" for _ in range(NUM_QUBITS))
                + f"  {_fmt_dur(row['elapsed']):>8}"
            )
        else:
            line = (
                f"{row['length']:>8} {row['length']*2:>6} "
                f"{row['overall']:>8.2f}% "
                + " ".join(f"{row['per_q'][i]:>6.2f}%" for i in range(NUM_QUBITS))
                + f"  {_fmt_dur(row['elapsed']):>8}"
            )
        logger.info(line)
    logger.info("=" * 78)


