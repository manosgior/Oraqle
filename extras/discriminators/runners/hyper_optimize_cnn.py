# Per-length CNN files generated by `helpers/extract_data_per_length.py`.
# Each file contains exactly `TARGET_STEPS` ds-steps regardless of trace
# length, with `ds_factor = trace_length // TARGET_STEPS` baked into the
# preprocessing. The CNN therefore sees a constant input shape across the
# whole sweep.
TARGET_STEPS = 50
CNN_FILE_PATTERN = (
    str(CNN_DATA) + "/Qubit_5Channel_target{target}_len{length}_{mode}.h5"
)
NUM_QUBITS = 5

# Architecture: m_param fixed (per user request); we only search lr / batch_size.
