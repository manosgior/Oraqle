"""
hyper_optimize_cnn.py
=====================
Dedicated Optuna hyper-optimization script for the multi-task CNN discriminator.

Differences vs. the CNN section in `hyper_optimize.py`:
  - `m_param` is fixed at 16 (only `lr` and `batch_size` are searched).
  - Adds a step-decay LR scheduler matching the reference Keras training script.
  - Data is loaded and preprocessed ONCE per trace length, then reused across
    every Optuna trial for that length (HDF5 I/O and normalization are not
    repeated 50x).
  - Train/val/test tensors live on the GPU for the duration of each trace
    length. Trials use `torch.randperm` + tensor indexing instead of a
    DataLoader, eliminating per-batch host->device transfer and the Python
    iterator overhead that otherwise dominates wall-clock on a model this
    small.
  - cuDNN benchmark mode is enabled (fixed input shape across the sweep).
  - Optuna trials run concurrently on a single GPU via threading
    (`study.optimize(n_jobs=N_PARALLEL_TRIALS)`). PyTorch CUDA kernels release
    the GIL, so multiple small CNN trainings can overlap on the A40.
  - Fixes the `study.best_trial.user_attrs["m_param"]` crash from the old
    runner (the attr was never set).
  - Fixes the data-shape branch: the H5 file stores `(N, T_ds, Q, IQ)`, which
    is correctly reshaped to `(N, 10, T_ds)` for Conv1d.

Run inside the project Docker container:
    python -m runners.hyper_optimize_cnn
"""

