def _save_csv_report(
    study: optuna.Study,
    model: nn.Module,
    trace_length: int,
    overall_acc: float,
    per_qubit_accs: list[float],
):
    best = study.best_trial
    total_params = sum(p.numel() for p in model.parameters())
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    filename = f"CNN_m{M_PARAM}_len{trace_length}_{timestamp}.csv"
    filepath = os.path.join(CSV_DIR, filename)

    row = {
        "timestamp": timestamp,
        "model_name": "CNN",
        "trace_length": trace_length,
        "target_steps": TARGET_STEPS,
        "downsample_factor": best.user_attrs.get("ds_factor", "N/A"),
        "m_param": M_PARAM,
        "optimizer": "Adam",
        "lr_schedule": f"step_decay(gamma={DECAY_RATE}, step={DECAY_STEP})",
        "learning_rate": best.params.get("lr", "N/A"),
        "batch_size": best.params.get("batch_size", "N/A"),
        "epochs": EPOCHS_PER_TRIAL,
        "n_optuna_trials": len(study.trials),
        "best_trial_number": best.number,
        "best_val_loss": f"{best.value:.6f}",
        "total_parameters": total_params,
        "overall_accuracy": f"{overall_acc:.4f}",
        **{f"qubit_{q}_accuracy": f"{per_qubit_accs[q]:.4f}"
           for q in range(NUM_QUBITS)},
        "device": str(DEVICE),
        "model_path": best.user_attrs.get("model_path", "N/A"),
    }

    with _FILE_LOCK:
        with open(filepath, "w", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=row.keys())
            writer.writeheader()
            writer.writerow(row)
    logger.info(f"CSV report saved: {filepath}")


