def _load_h5_split(filepath: str, is_test: bool, max_samples: int | None):
    """Load X, y from the CNN H5 file. Returns X with shape (N, T_ds, Q, IQ)."""
    if not os.path.exists(filepath):
        raise FileNotFoundError(f"CNN data file missing: {filepath}")

    file_mb = os.path.getsize(filepath) / (1024 * 1024)
    key_suffix = "test" if is_test else "train"
    t0 = time.perf_counter()
    logger.info(f"Loading {filepath}  ({file_mb:.1f} MB)")
    with h5py.File(filepath, "r") as hf:
        total = hf[f"X_{key_suffix}"].shape[0]
        if max_samples is not None and max_samples < total:
            rng = np.random.RandomState(SAMPLE_SEED)
            idx = np.sort(rng.choice(total, size=max_samples, replace=False))
            X = hf[f"X_{key_suffix}"][idx]
            y = hf[f"y_{key_suffix}"][idx]
            logger.info(
                f"  subsampled {key_suffix}: {total:,} -> {max_samples:,} traces"
            )
        else:
            X = hf[f"X_{key_suffix}"][:]
            y = hf[f"y_{key_suffix}"][:]
    logger.info(
        f"  loaded {key_suffix}: X={X.shape} y={y.shape} "
        f"in {_fmt_dur(time.perf_counter() - t0)}"
    )
    return X, y


def _to_channels_first(X: np.ndarray) -> np.ndarray:
    """Reshape the CNN data into (N, 10, T_ds) regardless of source layout.

    The extracted H5 file stores (N, T_ds, Q, IQ) = (N, 50, 5, 2). Some older
    intermediate formats already provide (N, 10, T_ds); we handle both.
    """
    if X.ndim == 4:
        N, T, Q, IQ = X.shape
        X = X.reshape(N, T, Q * IQ)              # (N, T, 10)
        return np.transpose(X, (0, 2, 1))        # (N, 10, T)
    if X.ndim == 3 and X.shape[1] == 10:
        return X                                 # already (N, 10, T)
    if X.ndim == 3 and X.shape[2] == 10:
        return np.transpose(X, (0, 2, 1))        # (N, T, 10) -> (N, 10, T)
    raise ValueError(f"Unexpected CNN data shape: {X.shape}")


def _labels_to_bits(y: np.ndarray) -> np.ndarray:
    """Convert packed integer state labels (0..31) to a (N, 5) bit matrix."""
    if y.ndim > 1:
        return y.astype(np.float32)
    bits = np.stack(
        [((y >> i) & 1).astype(np.float32) for i in range(NUM_QUBITS)], axis=1
    )
    return bits


def prepare_split_for_length(trace_length: int):
    """Load, slice, normalize, and split the training data for one trace length.

    Returns
    -------
    dict with keys:
        X_train, y_train, X_val, y_val   (float32 tensors on CPU)
        mean, std                        (np.ndarray, per-channel)
        ds_factor                        (int, raw -> ds decimation factor)
    """
    train_path = CNN_FILE_PATTERN.format(
        target=TARGET_STEPS, length=trace_length, mode="train"
    )
    X_raw, y_raw = _load_h5_split(
        train_path, is_test=False, max_samples=MAX_TRAIN_SAMPLES
    )

    X = _to_channels_first(X_raw).astype(np.float32)       # (N, 10, TARGET_STEPS)
    y = _labels_to_bits(y_raw)                             # (N, 5)

    if X.shape[2] != TARGET_STEPS:
        raise ValueError(
            f"{train_path} has {X.shape[2]} ds-steps; expected {TARGET_STEPS}. "
            "Regenerate with helpers/extract_data_per_length.py."
        )

    X_train, X_val, y_train, y_val = train_test_split(
        X, y, test_size=VAL_SPLIT, random_state=SAMPLE_SEED
    )

    # Per-channel z-score, stats computed on the training split only.
    mean = X_train.mean(axis=(0, 2), keepdims=True)
    std = X_train.std(axis=(0, 2), keepdims=True) + 1e-10
    X_train = (X_train - mean) / std
    X_val = (X_val - mean) / std

    # Push tensors to GPU once; every Optuna trial for this length shares
    # them via indexed sampling.
    return {
        "X_train": torch.from_numpy(X_train).to(DEVICE, non_blocking=True),
        "y_train": torch.from_numpy(y_train).to(DEVICE, non_blocking=True),
        "X_val": torch.from_numpy(X_val).to(DEVICE, non_blocking=True),
        "y_val": torch.from_numpy(y_val).to(DEVICE, non_blocking=True),
        "mean": mean,
        "std": std,
        "ds_factor": trace_length // TARGET_STEPS,
    }


def prepare_test_for_length(trace_length: int, mean: np.ndarray, std: np.ndarray):
    """Load + normalize the per-length test set using train-set statistics.

    Returns GPU-resident tensors so evaluation iterates with simple slicing.
    """
    test_path = CNN_FILE_PATTERN.format(
        target=TARGET_STEPS, length=trace_length, mode="test"
    )
    X_raw, y_raw = _load_h5_split(
        test_path, is_test=True, max_samples=MAX_TEST_SAMPLES
    )

    X = _to_channels_first(X_raw).astype(np.float32)
    y = _labels_to_bits(y_raw)

    X = (X - mean) / std
    return (
        torch.from_numpy(X).to(DEVICE, non_blocking=True),
        torch.from_numpy(y).to(DEVICE, non_blocking=True),
    )


